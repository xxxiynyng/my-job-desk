// "있으면 빼고 없으면 넣는다"가 8개 화면에 각각 복제돼 있었다. 동작은 종전과 동일하다.
// ─────────────────────────────────────────────────────────────

/** 있으면 제거, 없으면 추가한 **새 Set**을 돌려준다(원본 불변). */
export function toggleInSet<T>(set: ReadonlySet<T>, v: T): Set<T> {
  const n = new Set(set);
  if (n.has(v)) n.delete(v);
  else n.add(v);
  return n;
}
